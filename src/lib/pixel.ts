/** ドット絵は 16×16 の格子。`#` が塗り、`.` が透過。Agent 作の仮の絵（PO 決定 2026-09-18） */
export type Cell = { x: number; y: number };

export function cells(rows: readonly string[]): Cell[] {
  return rows.flatMap((row, y) => [...row].flatMap((ch, x) => (ch === '#' ? [{ x, y }] : [])));
}

